"""Export design-system/project/tokens.json to CSS for apps/hub-ui.

    python design-system/gen_tokens.py

Writes apps/hub-ui/src/styles/tokens.generated.css: @font-face rules (fonts are
self-hosted from design-system/project/fonts — no network fonts on the device),
night/day colour variables, spacing/radius/shadow/blur/size/motion variables and
one class per type style. Token names here are the names in code (6-build-stack.md).
Edit tokens.json, not the generated file.
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "project", "tokens.json")
OUT = os.path.join(HERE, "..", "apps", "hub-ui", "src", "styles", "tokens.generated.css")
FONT_URL = "../../../../design-system/project/{file}"  # relative to OUT

t = json.load(open(SRC, encoding="utf-8"))
lines = ["/* GENERATED by design-system/gen_tokens.py from design-system/project/tokens.json — do not edit. */", ""]

for f in t["type"]["fonts"]:
    lines.append("@font-face {")
    lines.append(f'  font-family: "{f["family"]}";')
    lines.append(f'  src: url("{FONT_URL.format(file=f["file"])}") format("woff2");')
    lines.append(f'  font-weight: {f["weight"]};')
    lines.append(f'  font-style: {f["style"]};')
    lines.append("  font-display: block;")
    lines.append("}")
lines.append("")


def block(selector: str, theme: str) -> None:
    lines.append(f"{selector} {{")
    lines.append(f"  color-scheme: {'dark' if theme == 'night' else 'light'};")
    for c in t["color"]["tokens"]:
        lines.append(f'  --{c["name"]}: {c["value"][theme]};')
    for s in t["shadow"]["tokens"]:
        lines.append(f'  --{s["name"]}: {s["value"][theme]};')
    lines.append("}")


block(':root, [data-theme="night"]', "night")
block('[data-theme="day"]', "day")
lines.append("")

lines.append(":root {")
for k, v in t["type"]["families"].items():
    lines.append(f"  --font-{k}: {v};")
for fam in ("spacing", "radius", "blur", "opacity", "size", "duration", "easing"):
    for tok in t[fam]["tokens"]:
        lines.append(f'  --{tok["name"]}: {tok["value"]};')
lines.append("  --text-scale: 1;")
lines.append("}")
lines.append("")

for g in t["type"]["groups"]:
    for s in g["styles"]:
        fam = s.get("family", g["family"])
        size = float(s["fontSize"].removesuffix("px"))
        lines.append(f'.{s["name"]} {{')
        lines.append(f"  font-family: var(--font-{fam});")
        lines.append(f"  font-size: calc({size:g}px * var(--text-scale));")
        lines.append(f'  line-height: {s["lineHeight"]};')
        lines.append(f'  font-weight: {s["fontWeight"]};')
        if "letterSpacing" in s:
            lines.append(f'  letter-spacing: {s["letterSpacing"]};')
        if s.get("fontStyle"):
            lines.append(f'  font-style: {s["fontStyle"]};')
        if s["name"] == "label":
            lines.append("  text-transform: uppercase;")
        lines.append("}")
lines.append("")

os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print("written", os.path.relpath(OUT, os.path.join(HERE, "..")))
